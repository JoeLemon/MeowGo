def category(key: str) -> str:
    """某个步骤类型属于哪一类（用于列表分组与下拉框分组）。"""
    if key in _SCREEN:
        return "操作屏幕"
    if key in _WAIT:
        return "等待与识别"
    if key in _FLOW:
        return "流程控制"
    return "数据与系统"


